import type { Item, ItemKind, Unit } from "./types";
import { tables } from "./verbs";

/*
 * Curriculum built from Ron Ragsdale's course materials (Parts I–III):
 *  - Part I: verbs by category, regular endings, the most common irregulars,
 *    and the "handles" (his explanations of why).
 *  - Part II: sentence construction, time frames, interrogatives.
 *  - Part III ("Stuff"): vocabulary grouped by category.
 *
 * Order follows his "Laws of Probability of Usage": start at the apex of the
 * bell curve with the most-used words and push outward. Concrete nouns a
 * child uses (family, food, animals, body) are interleaved early so the
 * verbs have something to act on right away.
 */

let unitId = "";
const slug = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function mk(kind: ItemKind) {
  return (es: string, en: string, opts: { alt?: string[]; note?: string } = {}): Item => ({
    id: `${unitId}:${slug(es)}`,
    es,
    en,
    kind,
    ...opts,
  });
}
const v = mk("verb");
const n = mk("noun");
const ph = mk("phrase");
const w = mk("word");

function unit(u: Omit<Unit, "items"> & { items: () => Item[] }): Unit {
  unitId = u.id;
  return { ...u, items: u.items() };
}

